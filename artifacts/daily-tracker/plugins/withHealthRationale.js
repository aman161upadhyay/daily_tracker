/**
 * Health Connect privacy rationale (Expo config plugin).
 *
 * Health Connect's permission dialog has a "privacy policy" link. Android sends
 * it as an intent — ACTION_SHOW_PERMISSIONS_RATIONALE through Android 13, the
 * VIEW_PERMISSION_USAGE alias from Android 14 — and react-native-health-connect
 * points both at MainActivity, which simply opens the app on Today: whoever
 * taps the link learns nothing about what the data is for.
 *
 * This plugin adds a tiny native trampoline, HealthRationaleActivity, that
 * forwards either intent to the app's own deep link
 * `daily-tracker://health-privacy` (app/health-privacy.tsx, an offline
 * explanation of what is read, where it stays and how to revoke it) and
 * finishes. It then retargets the alias and removes the rationale filter from
 * MainActivity.
 *
 * Order matters: Expo runs the manifest mod of a later plugin *before* an
 * earlier one, so this plugin must sit BEFORE "react-native-health-connect" in
 * app.json for its changes to land on top of that plugin's. The prebuild
 * check in docs/BUILD_ANDROID.md lists what the manifest must show.
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const { getMainActivityOrThrow, getMainApplicationOrThrow } = AndroidConfig.Manifest;

const ACTIVITY = 'HealthRationaleActivity';
const RATIONALE_ACTION = 'androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE';
const VIEW_PERMISSION_USAGE_ALIAS = 'ViewPermissionUsageActivity';
const RATIONALE_URI = 'daily-tracker://health-privacy';

const KOTLIN = (packageName) => `package ${packageName}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

/**
 * Health Connect's "privacy policy" entry point (ACTION_SHOW_PERMISSIONS_RATIONALE and
 * VIEW_PERMISSION_USAGE): opens the in-app explanation through the app's own deep link, then
 * leaves. Generated by plugins/withHealthRationale.js — edit the plugin, not this file.
 */
class ${ACTIVITY} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val open = Intent(Intent.ACTION_VIEW, Uri.parse("${RATIONALE_URI}"))
    open.setPackage(packageName)
    open.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    startActivity(open)
    finish()
  }
}
`;

const hasAction = (filter, name) => (filter.action || []).some((a) => a.$['android:name'] === name);

function withHealthRationale(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const packageName = cfg.android && cfg.android.package;
      if (!packageName) throw new Error('withHealthRationale: android.package is not set in app.json');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...packageName.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${ACTIVITY}.kt`), KOTLIN(packageName));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, async (cfg) => {
    const application = getMainApplicationOrThrow(cfg.modResults);
    const mainActivity = getMainActivityOrThrow(cfg.modResults);

    // The rationale intent is ours now, not MainActivity's.
    if (mainActivity['intent-filter']) {
      mainActivity['intent-filter'] = mainActivity['intent-filter'].filter((f) => !hasAction(f, RATIONALE_ACTION));
    }

    application.activity = application.activity || [];
    if (!application.activity.some((a) => a.$['android:name'] === `.${ACTIVITY}`)) {
      application.activity.push({
        $: {
          'android:name': `.${ACTIVITY}`,
          'android:exported': 'true',
          'android:excludeFromRecents': 'true',
          'android:noHistory': 'true',
          'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
        },
        'intent-filter': [{ action: [{ $: { 'android:name': RATIONALE_ACTION } }] }],
      });
    }

    // Android 14+: the alias react-native-health-connect adds, pointed at the trampoline. Created
    // here when that plugin has not run yet (or was removed), so the Android 14 path never dangles.
    application['activity-alias'] = application['activity-alias'] || [];
    const alias = application['activity-alias'].find((a) => a.$['android:name'] === VIEW_PERMISSION_USAGE_ALIAS);
    if (alias) {
      alias.$['android:targetActivity'] = `.${ACTIVITY}`;
    } else {
      application['activity-alias'].push({
        $: {
          'android:name': VIEW_PERMISSION_USAGE_ALIAS,
          'android:exported': 'true',
          'android:targetActivity': `.${ACTIVITY}`,
          'android:permission': 'android.permission.START_VIEW_PERMISSION_USAGE',
        },
        'intent-filter': [
          {
            action: [{ $: { 'android:name': 'android.intent.action.VIEW_PERMISSION_USAGE' } }],
            category: [{ $: { 'android:name': 'android.intent.category.HEALTH_PERMISSIONS' } }],
          },
        ],
      });
    }
    return cfg;
  });
}

module.exports = withHealthRationale;
