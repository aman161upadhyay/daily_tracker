/**
 * Android Auto Backup rules (Expo config plugin).
 *
 * Only `files/backup/` — the whole-state snapshot that BackupSync writes in the
 * export format — is backed up and transferred between devices. The live
 * SQLite database (files/SQLite, with its WAL) and SharedPreferences are left
 * out: a database copied mid-write restores torn, and stale scheduler state
 * from another phone is worse than none.
 *
 * Health data only ever goes to Google's servers encrypted with the phone's own
 * lock screen, and that guarantee is expressed per Android version:
 * - Android 12+ (API 31): data_extraction_rules with
 *   `disableIfNoEncryptionCapabilities`
 * - Android 9–11 (API 28–30): full-backup-content with
 *   `requireFlags="clientSideEncryption"` (res/xml-v28)
 * - Android 8.x (API 26–27): the flag does not exist, so nothing is included at
 *   all (res/xml) — the manual export is the way to move data there
 * Device-to-device transfer (cable / local) carries the snapshot on every version.
 *
 * Verify after prebuild: android/app/src/main/AndroidManifest.xml carries
 * android:fullBackupContent and android:dataExtractionRules, and the XML files
 * exist under res/xml and res/xml-v28.
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

// Android 8.x: an <include> that matches nothing. (A rules file with no <include>
// would back up *everything*, and <exclude> alone cannot express "nothing".)
const BACKUP_RULES_LEGACY = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js (Android 8.x): no cloud backup, it cannot be lock-screen encrypted here. -->
<full-backup-content>
  <include domain="file" path="backup-requires-android-9/" />
</full-backup-content>
`;

const BACKUP_RULES_V28 = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js (Android 9–11): only with lock-screen encryption. -->
<full-backup-content>
  <include domain="file" path="backup/" requireFlags="clientSideEncryption" />
</full-backup-content>
`;

const EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js (Android 12 and higher). -->
<data-extraction-rules>
  <cloud-backup disableIfNoEncryptionCapabilities="true">
    <include domain="file" path="backup/" />
  </cloud-backup>
  <device-transfer>
    <include domain="file" path="backup/" />
  </device-transfer>
</data-extraction-rules>
`;

function withBackupRules(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      const xmlDir = path.join(res, 'xml');
      const xmlV28 = path.join(res, 'xml-v28');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.mkdirSync(xmlV28, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'backup_rules.xml'), BACKUP_RULES_LEGACY);
      fs.writeFileSync(path.join(xmlV28, 'backup_rules.xml'), BACKUP_RULES_V28);
      fs.writeFileSync(path.join(xmlDir, 'data_extraction_rules.xml'), EXTRACTION_RULES);
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:allowBackup'] = 'true';
    app.$['android:fullBackupContent'] = '@xml/backup_rules';
    app.$['android:dataExtractionRules'] = '@xml/data_extraction_rules';
    return cfg;
  });
}

module.exports = withBackupRules;
